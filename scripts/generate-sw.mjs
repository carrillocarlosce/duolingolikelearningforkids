import { createHash } from "node:crypto";
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { BASE_PATH } from "../base-path.mjs";
import { precacheUrls } from "./precache-urls.mjs";

const outDir = path.join(process.cwd(), "out");
if (!existsSync(outDir)) {
  console.error("Missing out/. Run next build first.");
  process.exit(1);
}

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else files.push(path.relative(outDir, full));
  }
  return files;
}

const urls = precacheUrls(walk(outDir), BASE_PATH);
if (!urls.includes(`${BASE_PATH}/`) || !urls.some((url) => url.includes(`${BASE_PATH}/_next/`))) {
  console.error("Precache list is missing the app shell or Next.js assets.");
  process.exit(1);
}

const hash = createHash("sha256").update(urls.join("\n")).digest("hex").slice(0, 10);
const cacheName = `pipos-market-${hash}`;
const shell = `${BASE_PATH}/`;

const source = `/* Generated by scripts/generate-sw.mjs. Do not edit. */
const CACHE = ${JSON.stringify(cacheName)};
const BASE = ${JSON.stringify(BASE_PATH)};
const SHELL = ${JSON.stringify(shell)};
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname !== BASE && !url.pathname.startsWith(BASE + "/")) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(request, { ignoreSearch: true });
      if (cached) return cached;
      try {
        const response = await fetch(request);
        if (response && response.ok && response.type === "basic") {
          await cache.put(request, response.clone());
        }
        return response;
      } catch (error) {
        if (request.mode === "navigate") {
          const fallback = (await cache.match(SHELL)) || (await cache.match(SHELL + "index.html"));
          if (fallback) return fallback;
        }
        throw error;
      }
    })(),
  );
});
`;

writeFileSync(path.join(outDir, "sw.js"), source);
if (!source.includes(BASE_PATH) || !existsSync(path.join(outDir, "sw.js"))) {
  console.error("Service worker was not written with the project-site base path.");
  process.exit(1);
}
console.log(`Wrote out/sw.js (${urls.length} URLs, ${cacheName}).`);
